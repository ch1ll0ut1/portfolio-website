/**
 * Writes a `.d.ts` next to every CSS Module, naming the classes it defines.
 *
 * Next.js types every CSS Module as `{ [key: string]: string }`. Under
 * `noUncheckedIndexedAccess` that makes each `styles.foo` read as
 * `string | undefined`, and it never catches a misspelt class name either: a
 * typo is silently `undefined` and the element renders unstyled. Declaring the
 * real class names fixes both — a known class is a plain `string`, an unknown
 * one is a type error.
 *
 * The declarations are committed, so the editor, `tsc` and `next build` all see
 * them without a generation step. After adding or renaming a class, run
 * `pnpm css-types`; CI runs `pnpm css-types --check` and fails on drift.
 *
 * Usage:
 *   node scripts/css-module-types.mjs [--check]
 */

import { readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIRS = ['app', 'components'];
const CHECK = process.argv.includes('--check');

/** Every file under `dir` whose name ends in `suffix`. */
const findFiles = async (dir, suffix) => {
    const entries = await readdir(dir, { withFileTypes: true });
    const nested = await Promise.all(entries.map((entry) => {
        const path = join(dir, entry.name);

        if (entry.isDirectory()) {
            return findFiles(path, suffix);
        }

        return entry.name.endsWith(suffix) ? [path] : [];
    }));

    return nested.flat();
};

/**
 * The local class names a stylesheet defines.
 *
 * Only selector preludes (the text before each `{`) are read, after comments
 * and strings are blanked, so a `.5s` duration or a dotted `content` string is
 * never mistaken for a class. `:global(...)` names belong to the page, not to
 * the module, and are skipped.
 */
const classNames = (css) => {
    const stripped = css
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/'[^']*'|"[^"]*"/g, '\'\'')
        .replace(/:global\([^)]*\)/g, '');
    const names = new Set();

    for (const [, prelude] of stripped.matchAll(/([^{};]*)\{/g)) {
        for (const [, name] of prelude.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
            names.add(name);
        }
    }

    return [...names].sort();
};

const declaration = names => [
    '// Generated by scripts/css-module-types.mjs. Do not edit; run `pnpm css-types`.',
    'declare const styles: {',
    ...names.map(name => `    readonly ${/^[a-zA-Z_$][\w$]*$/.test(name) ? name : `'${name}'`}: string;`),
    '};',
    'export default styles;',
    '',
].join('\n');

const main = async () => {
    const find = async suffix => (await Promise.all(SOURCE_DIRS.map(dir => findFiles(join(ROOT, dir), suffix)))).flat();
    const modules = await find('.module.css');
    const stale = [];

    // A declaration whose stylesheet is gone would keep a deleted module importable.
    for (const target of await find('.module.css.d.ts')) {
        if (modules.includes(target.slice(0, -'.d.ts'.length))) {
            continue;
        }

        if (CHECK) {
            stale.push(relative(ROOT, target));
        }
        else {
            await unlink(target);
        }
    }

    for (const file of modules) {
        const target = `${file}.d.ts`;
        const expected = declaration(classNames(await readFile(file, 'utf8')));
        const current = await readFile(target, 'utf8').catch(() => null);

        if (current === expected) {
            continue;
        }

        if (CHECK) {
            stale.push(relative(ROOT, target));
        }
        else {
            await writeFile(target, expected);
        }
    }

    if (stale.length > 0) {
        console.error(`CSS Module types are out of date — run \`pnpm css-types\`:\n  ${stale.join('\n  ')}`);
        process.exitCode = 1;
    }
};

await main();
